#!/usr/bin/env bash
# Pin the exact packages (and their SHA-256 checksums) that go into the Lambda functions, for Lambda's
# Linux on ARM with Python 3.13. Deploys install only these (pip --require-hashes): a new or tampered
# release can't slip in. Run this after changing requirements.txt, check the diff, and commit both.
set -euo pipefail
cd "$(dirname "$0")"
wheels="$(mktemp -d)"
trap 'rm -rf "$wheels"' EXIT
python3 -m pip download --quiet --dest "$wheels" --requirement requirements.txt \
  --platform manylinux2014_aarch64 --implementation cp --python-version 3.13 --only-binary=:all:
python3 - "$wheels" > requirements.lock.txt <<'PY'
import hashlib, pathlib, re, sys
print("# Generated by update-lock.sh from requirements.txt: exact packages for Lambda (Python 3.13, ARM). Don't edit by hand.")
for wheel in sorted(pathlib.Path(sys.argv[1]).glob("*.whl"), key=lambda p: p.name.lower()):
    name, version = wheel.name.split("-")[:2]
    digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
    print(f"{re.sub(r'[-_.]+', '-', name).lower()}=={version} \\\n    --hash=sha256:{digest}")
PY
echo "Wrote requirements.lock.txt ($(grep -c '==' requirements.lock.txt) packages)"
